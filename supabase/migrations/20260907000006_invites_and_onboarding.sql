-- Allow system provision flag to bypass immutability trigger for official invite acceptance
CREATE OR REPLACE FUNCTION public.enforce_profile_role_immutability()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    -- If internal system provision flag is active, allow promotion
    IF pg_catalog.current_setting('app.system_role_provision', true) = 'true' THEN
        RETURN NEW;
    END IF;

    -- If role_id is being changed and the actor is not an admin, reject transaction
    IF OLD.role_id IS DISTINCT FROM NEW.role_id THEN
        IF auth.uid() IS NOT NULL AND NOT private.is_admin(auth.uid()) THEN
            RAISE EXCEPTION 'Acesso Negado: A alteração de papéis (roles) é estritamente restrita a administradores.';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

