-- Accept professional invite transactionally
CREATE OR REPLACE FUNCTION private.accept_professional_invite(
    p_token_hash TEXT,
    p_user_id UUID,
    p_full_name TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_invite public.professional_invites%ROWTYPE;
BEGIN
    SELECT * INTO v_invite
    FROM public.professional_invites
    WHERE token_hash = p_token_hash
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'INVITE_NOT_FOUND' USING ERRCODE = 'P0002';
    END IF;

    IF v_invite.accepted_at IS NOT NULL THEN
        RAISE EXCEPTION 'INVITE_ALREADY_USED' USING ERRCODE = 'P0003';
    END IF;

    IF v_invite.revoked_at IS NOT NULL THEN
        RAISE EXCEPTION 'INVITE_REVOKED' USING ERRCODE = 'P0004';
    END IF;

    IF v_invite.expires_at < pg_catalog.timezone('utc', pg_catalog.now()) THEN
        RAISE EXCEPTION 'INVITE_EXPIRED' USING ERRCODE = 'P0005';
    END IF;

    -- Enable system provision flag locally for this transaction
    PERFORM pg_catalog.set_config('app.system_role_provision', 'true', true);

    -- Update profile role to exact invited role
    UPDATE public.profiles
    SET role_id = v_invite.role_id,
        full_name = COALESCE(NULLIF(TRIM(p_full_name), ''), full_name)
    WHERE id = p_user_id;

    -- Delete dummy patient record if it was auto-created by auth trigger
    DELETE FROM public.patients WHERE id = p_user_id;

    -- Ensure professional profile exists
    INSERT INTO public.professional_profiles (id, professional_type)
    VALUES (p_user_id, v_invite.role_id)
    ON CONFLICT (id) DO UPDATE SET professional_type = EXCLUDED.professional_type;

    -- If org is specified, add as member
    IF v_invite.organization_id IS NOT NULL THEN
        INSERT INTO public.organization_members (organization_id, user_id, role_in_org)
        VALUES (v_invite.organization_id, p_user_id, 'member')
        ON CONFLICT (organization_id, user_id) DO NOTHING;
    END IF;

    -- Mark invite as accepted
    UPDATE public.professional_invites
    SET accepted_by = p_user_id,
        accepted_at = pg_catalog.timezone('utc', pg_catalog.now())
    WHERE id = v_invite.id;

    -- Reset provision flag
    PERFORM pg_catalog.set_config('app.system_role_provision', 'false', true);

    -- Audit log
    INSERT INTO public.audit_logs (
        actor_id,
        action,
        entity_type,
        entity_id,
        organization_id,
        metadata
    ) VALUES (
        p_user_id,
        'professional_invite.accepted',
        'professional_invites',
        v_invite.id::text,
        v_invite.organization_id,
        jsonb_build_object('role_id', v_invite.role_id, 'email', v_invite.email)
    );

    RETURN jsonb_build_object(
        'success', TRUE,
        'role_id', v_invite.role_id,
        'organization_id', v_invite.organization_id
    );
END;
$$;

GRANT EXECUTE ON FUNCTION private.accept_professional_invite(TEXT, UUID, TEXT) TO authenticated;

