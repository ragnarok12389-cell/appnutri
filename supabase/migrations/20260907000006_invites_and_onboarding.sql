-- ------------------------------------------------------------------------------
-- 9. ATOMIC RPC FUNCTION: ACCEPT PATIENT INVITE (Concurrency & Double-Spend Proof)
-- ------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION private.accept_patient_invite(
    p_token_hash TEXT,
    p_patient_id UUID
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_invite public.patient_invites%ROWTYPE;
    v_prof_type TEXT;
    v_link_type TEXT;
    v_existing_link_id UUID;
BEGIN
    -- 1. Concurrency lock: row-level lock on the specific invite
    SELECT * INTO v_invite
    FROM public.patient_invites
    WHERE token_hash = p_token_hash
    FOR UPDATE;

    -- 2. Validate invite existence
    IF NOT FOUND THEN
        RAISE EXCEPTION 'INVITE_NOT_FOUND' USING ERRCODE = 'P0002';
    END IF;

    -- 3. Validate revocation
    IF v_invite.revoked_at IS NOT NULL OR v_invite.status = 'revoked' THEN
        RAISE EXCEPTION 'INVITE_REVOKED' USING ERRCODE = 'P0004';
    END IF;

    -- 4. Validate expiration
    IF v_invite.expires_at < pg_catalog.timezone('utc', pg_catalog.now()) OR v_invite.status = 'expired' THEN
        UPDATE public.patient_invites
        SET status = 'expired'
        WHERE id = v_invite.id;
        RAISE EXCEPTION 'INVITE_EXPIRED' USING ERRCODE = 'P0005';
    END IF;

    -- 5. Validate status: MUST be pending
    IF v_invite.status <> 'pending' THEN
        RAISE EXCEPTION 'INVITE_ALREADY_USED_OR_INVALID' USING ERRCODE = 'P0003';
    END IF;

    -- 6. Ensure patient record exists in public.patients
    INSERT INTO public.patients (id)
    VALUES (p_patient_id)
    ON CONFLICT (id) DO NOTHING;

    -- 7. Retrieve professional type to determine link_type safely
    SELECT professional_type INTO v_prof_type
    FROM public.professional_profiles
    WHERE id = v_invite.professional_id;

    IF v_prof_type = 'influencer' THEN
        v_link_type := 'influencer_referral';
    ELSE
        v_link_type := 'direct';
    END IF;

    -- 8. Check if active link already exists between this pair
    SELECT id INTO v_existing_link_id
    FROM public.professional_patient_links
    WHERE professional_id = v_invite.professional_id
      AND patient_id = p_patient_id
      AND status = 'active';

    IF v_existing_link_id IS NULL THEN
        -- Create active primary link
        INSERT INTO public.professional_patient_links (
            professional_id,
            patient_id,
            organization_id,
            is_primary,
            status,
            link_type,
            notes
        ) VALUES (
            v_invite.professional_id,
            p_patient_id,
            v_invite.organization_id,
            TRUE,
            'active',
            v_link_type,
            'Linked via invite ' || v_invite.id::text
        );
    END IF;

    -- 9. Mark invite as accepted (Consumes token atomicity)
    UPDATE public.patient_invites
    SET status = 'accepted',
        accepted_by = p_patient_id,
        accepted_at = pg_catalog.timezone('utc', pg_catalog.now())
    WHERE id = v_invite.id;

    -- 10. Write audit log entry
    INSERT INTO public.audit_logs (
        actor_id,
        action,
        entity_type,
        entity_id,
        organization_id,
        metadata
    ) VALUES (
        p_patient_id,
        'invite.accepted',
        'patient_invites',
        v_invite.id::text,
        v_invite.organization_id,
        jsonb_build_object(
            'professional_id', v_invite.professional_id,
            'link_type', v_link_type,
            'organization_id', v_invite.organization_id
        )
    );

    RETURN jsonb_build_object(
        'success', TRUE,
        'invite_id', v_invite.id,
        'professional_id', v_invite.professional_id,
        'organization_id', v_invite.organization_id,
        'link_type', v_link_type
    );
END;
$$;

-- Grant execution to authenticated role
GRANT EXECUTE ON FUNCTION private.accept_patient_invite(TEXT, UUID) TO authenticated;

-- ------------------------------------------------------------------------------
-- 10. PUBLIC RPC FUNCTION: VALIDATE PATIENT INVITE (Safe Metadata for /invite/[token])
-- ------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION private.validate_patient_invite(
    p_token_hash TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_invite public.patient_invites%ROWTYPE;
    v_prof_name TEXT;
    v_prof_type TEXT;
    v_org_name TEXT;
BEGIN
    SELECT * INTO v_invite
    FROM public.patient_invites
    WHERE token_hash = p_token_hash;

    IF NOT FOUND THEN
        RETURN jsonb_build_object('valid', FALSE, 'reason', 'not_found');
    END IF;

    IF v_invite.revoked_at IS NOT NULL OR v_invite.status = 'revoked' THEN
        RETURN jsonb_build_object('valid', FALSE, 'reason', 'revoked');
    END IF;

    IF v_invite.expires_at < pg_catalog.timezone('utc', pg_catalog.now()) OR v_invite.status = 'expired' THEN
        RETURN jsonb_build_object('valid', FALSE, 'reason', 'expired');
    END IF;

    IF v_invite.status <> 'pending' THEN
        RETURN jsonb_build_object('valid', FALSE, 'reason', 'already_used');
    END IF;

    -- Fetch professional and org details
    SELECT pr.full_name, pp.professional_type
    INTO v_prof_name, v_prof_type
    FROM public.professional_profiles pp
    JOIN public.profiles pr ON pr.id = pp.id
    WHERE pp.id = v_invite.professional_id;

    IF v_invite.organization_id IS NOT NULL THEN
        SELECT name INTO v_org_name
        FROM public.organizations
        WHERE id = v_invite.organization_id;
    END IF;

    RETURN jsonb_build_object(
        'valid', TRUE,
        'professional_name', v_prof_name,
        'professional_type', v_prof_type,
        'organization_name', v_org_name,
        'email', v_invite.email
    );
END;
$$;

GRANT EXECUTE ON FUNCTION private.validate_patient_invite(TEXT) TO anon, authenticated;

