-- 6. RLS POLICIES FOR PROFESSIONAL_INVITES (Strictly Admin)
-- ------------------------------------------------------------------------------
CREATE POLICY "Admins can view professional invites"
    ON public.professional_invites FOR SELECT
    TO authenticated
    USING (private.is_admin(auth.uid()));

CREATE POLICY "Admins can insert professional invites"
    ON public.professional_invites FOR INSERT
    TO authenticated
    WITH CHECK (private.is_admin(auth.uid()) AND created_by = auth.uid());

CREATE POLICY "Admins can update professional invites"
    ON public.professional_invites FOR UPDATE
    TO authenticated
    USING (private.is_admin(auth.uid()));

CREATE POLICY "Admins can delete professional invites"
    ON public.professional_invites FOR DELETE
    TO authenticated
    USING (private.is_admin(auth.uid()));

-- ------------------------------------------------------------------------------
-- 7. RLS POLICIES FOR PATIENT_INVITES
-- ------------------------------------------------------------------------------
-- Professionals can only view invites they created. Admins can view all. Patients CANNOT view any.
CREATE POLICY "Professionals and Admins can view patient invites"
    ON public.patient_invites FOR SELECT
    TO authenticated
    USING (
        (professional_id = auth.uid() AND private.is_professional(auth.uid()))
        OR private.is_admin(auth.uid())
    );

-- Professionals can insert invites ONLY for themselves. Admins can insert.
CREATE POLICY "Professionals and Admins can insert patient invites"
    ON public.patient_invites FOR INSERT
    TO authenticated
    WITH CHECK (
        (professional_id = auth.uid() AND private.is_professional(auth.uid()))
        OR private.is_admin(auth.uid())
    );

-- Professionals can update/revoke their own invites.
CREATE POLICY "Professionals and Admins can update patient invites"
    ON public.patient_invites FOR UPDATE
    TO authenticated
    USING (
        (professional_id = auth.uid() AND private.is_professional(auth.uid()))
        OR private.is_admin(auth.uid())
    );

-- ------------------------------------------------------------------------------
-- 8. RLS POLICIES FOR PATIENT_ONBOARDING
