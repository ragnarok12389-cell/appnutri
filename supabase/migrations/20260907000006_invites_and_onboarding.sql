-- 2. PROFESSIONAL_INVITES (Managed strictly by ADMIN)
CREATE TABLE IF NOT EXISTS public.professional_invites (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email TEXT NOT NULL,
    role_id TEXT NOT NULL CHECK (role_id IN ('nutritionist', 'influencer')),
    organization_id UUID REFERENCES public.organizations(id) ON DELETE SET NULL,
    token_hash TEXT NOT NULL UNIQUE,
    created_by UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    accepted_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.timezone('utc', pg_catalog.now())
);

CREATE INDEX IF NOT EXISTS idx_prof_invites_token ON public.professional_invites(token_hash);
CREATE INDEX IF NOT EXISTS idx_prof_invites_email ON public.professional_invites(email);
CREATE INDEX IF NOT EXISTS idx_prof_invites_created_by ON public.professional_invites(created_by);

COMMENT ON TABLE public.professional_invites IS 'Cryptographic invites for Nutritionists and Influencers generated strictly by Admins.';

-- 3. PATIENT_INVITES (Generated by Professionals or Admins)
CREATE TABLE IF NOT EXISTS public.patient_invites (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    professional_id UUID NOT NULL REFERENCES public.professional_profiles(id) ON DELETE CASCADE,
    organization_id UUID REFERENCES public.organizations(id) ON DELETE SET NULL,
    email TEXT,
    token_hash TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL CHECK (status IN ('pending', 'accepted', 'expired', 'revoked')) DEFAULT 'pending',
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_by UUID REFERENCES public.patients(id) ON DELETE SET NULL,
    accepted_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT pg_catalog.timezone('utc', pg_catalog.now())
);

CREATE INDEX IF NOT EXISTS idx_patient_invites_token ON public.patient_invites(token_hash);
CREATE INDEX IF NOT EXISTS idx_patient_invites_prof ON public.patient_invites(professional_id);
CREATE INDEX IF NOT EXISTS idx_patient_invites_status ON public.patient_invites(status);

COMMENT ON TABLE public.patient_invites IS 'Cryptographic invites generated by professionals to link patients safely.';

